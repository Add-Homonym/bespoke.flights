/** Postgres schema. Idempotent: safe to run on every cold start. */
export const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  phone         TEXT,
  password_hash TEXT,            -- development only, Neon Auth holds credentials in production
  auth_id       TEXT,            -- neon_auth."user".id
  name          TEXT NOT NULL,
  role          TEXT NOT NULL CHECK(role IN ('customer','operator','admin')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS operators (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL UNIQUE REFERENCES users(id),
  company_name  TEXT NOT NULL,
  certificate   TEXT,
  status        TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','suspended')),
  -- Contact preferences
  contact_method TEXT NOT NULL DEFAULT 'email' CHECK(contact_method IN ('email','text','both')),
  contact_email  TEXT,
  contact_phone  TEXT,
  -- Operator profile for matching
  safety_rating  TEXT,
  fleet_types    TEXT,   -- JSON array: ["light","mid","heavy","ultra_long"]
  markets        TEXT,   -- JSON array: ["hi_inter","mainland_hi","west","east",...]
  range_max_nm   INTEGER,
  hi_capable     INTEGER NOT NULL DEFAULT 0,
  transoceanic   INTEGER NOT NULL DEFAULT 0,
  notes          TEXT,
  -- Stripe Connect payout account
  stripe_account_id        TEXT,
  stripe_charges_enabled   INTEGER NOT NULL DEFAULT 0,
  stripe_payouts_enabled   INTEGER NOT NULL DEFAULT 0,
  stripe_details_submitted INTEGER NOT NULL DEFAULT 0,
  platform_fee_bps         INTEGER,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS aircraft (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id   INTEGER NOT NULL REFERENCES operators(id),
  tail_number   TEXT NOT NULL,
  type          TEXT NOT NULL,
  capacity      INTEGER NOT NULL,
  range_nm      INTEGER,
  year          INTEGER,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS booking_requests (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     INTEGER NOT NULL REFERENCES users(id),
  status          TEXT NOT NULL DEFAULT 'open'
                  CHECK(status IN ('open','quoted','booked','cancelled','completed')),
  passenger_count INTEGER NOT NULL DEFAULT 1,
  notes           TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS booking_legs (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id      INTEGER NOT NULL REFERENCES booking_requests(id) ON DELETE CASCADE,
  leg_order       INTEGER NOT NULL,
  origin_code     TEXT NOT NULL,
  origin_name     TEXT,
  dest_code       TEXT NOT NULL,
  dest_name       TEXT,
  departure_date  TEXT NOT NULL,
  departure_time  TEXT,
  UNIQUE(request_id, leg_order)
);

CREATE TABLE IF NOT EXISTS quotes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id    INTEGER NOT NULL REFERENCES booking_requests(id),
  operator_id   INTEGER NOT NULL REFERENCES operators(id),
  aircraft_id   INTEGER REFERENCES aircraft(id),
  price_cents   BIGINT NOT NULL,
  currency      TEXT NOT NULL DEFAULT 'USD',
  message       TEXT,
  status        TEXT NOT NULL DEFAULT 'pending'
                CHECK(status IN ('pending','accepted','rejected','withdrawn')),
  valid_until   TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Outreach log: tracks every RFQ dispatched to an operator
CREATE TABLE IF NOT EXISTS outreach_log (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id    INTEGER NOT NULL REFERENCES booking_requests(id),
  operator_id   INTEGER NOT NULL REFERENCES operators(id),
  method        TEXT NOT NULL CHECK(method IN ('email','text','both','pending')),
  match_score   INTEGER NOT NULL DEFAULT 0,
  rfq_subject   TEXT,
  rfq_body      TEXT NOT NULL,
  status        TEXT NOT NULL DEFAULT 'sent' CHECK(status IN ('queued','sent','delivered','failed','responded')),
  sent_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  responded_at  TIMESTAMPTZ,
  UNIQUE(request_id, operator_id)
);

-- Discovered operators: found via FAA registry scrape, pending outreach
CREATE TABLE IF NOT EXISTS discovered_operators (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name       TEXT NOT NULL,
  dba_name           TEXT,
  certificate_number TEXT UNIQUE,
  contact_email      TEXT,
  phone              TEXT,
  address            TEXT,
  city               TEXT,
  state              TEXT,
  zip                TEXT,
  status             TEXT NOT NULL DEFAULT 'new'
                     CHECK(status IN ('new','no_email','emailed','registered','opted_out','bounced')),
  source             TEXT NOT NULL DEFAULT 'faa_registry',
  discovered_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  emailed_at         TIMESTAMPTZ,
  invite_resend_id   TEXT,
  notes              TEXT
);

-- Payments: one row per checkout attempt for an accepted quote.
-- Funds are collected by the platform and routed to the operator's
-- Stripe Connect account, minus the platform fee.
CREATE TABLE IF NOT EXISTS payments (
  id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id                 INTEGER NOT NULL REFERENCES booking_requests(id),
  quote_id                   INTEGER NOT NULL REFERENCES quotes(id),
  customer_id                INTEGER NOT NULL REFERENCES users(id),
  operator_id                INTEGER NOT NULL REFERENCES operators(id),
  amount_cents               BIGINT NOT NULL,
  platform_fee_cents         BIGINT NOT NULL,
  operator_payout_cents      BIGINT NOT NULL,
  refunded_cents             BIGINT NOT NULL DEFAULT 0,
  currency                   TEXT NOT NULL DEFAULT 'USD',
  status                     TEXT NOT NULL DEFAULT 'pending'
                             CHECK(status IN ('pending','processing','succeeded','failed','canceled','refunded','partially_refunded')),
  provider                   TEXT NOT NULL DEFAULT 'stripe' CHECK(provider IN ('stripe','stub')),
  stripe_checkout_session_id TEXT UNIQUE,
  stripe_payment_intent_id   TEXT UNIQUE,
  stripe_destination_account TEXT,
  checkout_url               TEXT,
  failure_reason             TEXT,
  dispute_status             TEXT,
  created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
  paid_at                    TIMESTAMPTZ
);

-- Refund ledger. refunded_cents on payments is the running total.
CREATE TABLE IF NOT EXISTS refunds (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id       INTEGER NOT NULL REFERENCES payments(id),
  amount_cents     BIGINT NOT NULL,
  reason           TEXT,
  stripe_refund_id TEXT UNIQUE,
  initiated_by     INTEGER REFERENCES users(id),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Processed Stripe webhook events, for idempotency.
CREATE TABLE IF NOT EXISTS payment_events (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stripe_event_id TEXT NOT NULL UNIQUE,
  type            TEXT NOT NULL,
  received_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at    TIMESTAMPTZ
);

-- Private trip-sheet links an operator shares with their own staff
-- (dispatch, crew, catering). Anyone holding the token can view the sheet
-- until it is revoked or expires.
CREATE TABLE IF NOT EXISTS trip_shares (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id  INTEGER NOT NULL REFERENCES booking_requests(id),
  operator_id INTEGER NOT NULL REFERENCES operators(id),
  token       TEXT NOT NULL UNIQUE,
  created_by  INTEGER REFERENCES users(id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at  TIMESTAMPTZ NOT NULL,
  revoked_at  TIMESTAMPTZ
);

-- Operator staff who receive automatic alerts (they do not log in).
CREATE TABLE IF NOT EXISTS operator_staff (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id       INTEGER NOT NULL REFERENCES operators(id),
  name              TEXT NOT NULL,
  role              TEXT,
  email             TEXT,
  phone             TEXT,
  notify_email      INTEGER NOT NULL DEFAULT 1,
  notify_sms        INTEGER NOT NULL DEFAULT 0,
  on_new_request    INTEGER NOT NULL DEFAULT 0,
  on_booking        INTEGER NOT NULL DEFAULT 1,
  on_cancellation   INTEGER NOT NULL DEFAULT 1,
  active            INTEGER NOT NULL DEFAULT 1,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Every alert sent to a staff member. The unique key makes alerts
-- idempotent: a retried webhook cannot notify the same person twice.
CREATE TABLE IF NOT EXISTS staff_notifications (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id    INTEGER NOT NULL REFERENCES operator_staff(id) ON DELETE CASCADE,
  event_key   TEXT NOT NULL,
  channel     TEXT NOT NULL CHECK(channel IN ('email','sms')),
  status      TEXT NOT NULL CHECK(status IN ('sent','failed')),
  error       TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(staff_id, event_key, channel)
);

-- Private, revocable link to an operator's live company board (for staff
-- without logins, e.g. a screen in dispatch).
CREATE TABLE IF NOT EXISTS operator_boards (
  operator_id INTEGER PRIMARY KEY REFERENCES operators(id),
  token       TEXT NOT NULL UNIQUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_booking_requests_customer ON booking_requests(customer_id);
CREATE INDEX IF NOT EXISTS idx_booking_requests_status ON booking_requests(status);
CREATE INDEX IF NOT EXISTS idx_booking_legs_request ON booking_legs(request_id);
CREATE INDEX IF NOT EXISTS idx_quotes_request ON quotes(request_id);
CREATE INDEX IF NOT EXISTS idx_quotes_operator ON quotes(operator_id);
CREATE INDEX IF NOT EXISTS idx_aircraft_operator ON aircraft(operator_id);
CREATE INDEX IF NOT EXISTS idx_outreach_request ON outreach_log(request_id);
CREATE INDEX IF NOT EXISTS idx_outreach_operator ON outreach_log(operator_id);
CREATE INDEX IF NOT EXISTS idx_operators_status ON operators(status);
CREATE INDEX IF NOT EXISTS idx_discovered_status ON discovered_operators(status);
CREATE INDEX IF NOT EXISTS idx_discovered_cert ON discovered_operators(certificate_number);
CREATE INDEX IF NOT EXISTS idx_discovered_state ON discovered_operators(state);
CREATE INDEX IF NOT EXISTS idx_payments_request ON payments(request_id);
CREATE INDEX IF NOT EXISTS idx_payments_quote ON payments(quote_id);
CREATE INDEX IF NOT EXISTS idx_payments_operator ON payments(operator_id);
CREATE INDEX IF NOT EXISTS idx_payments_status ON payments(status);
CREATE INDEX IF NOT EXISTS idx_refunds_payment ON refunds(payment_id);
CREATE INDEX IF NOT EXISTS idx_trip_shares_request ON trip_shares(request_id, operator_id);
CREATE INDEX IF NOT EXISTS idx_operator_staff_operator ON operator_staff(operator_id);

-- Neon Auth: link app profiles to neon_auth users. Existing databases predate these.
ALTER TABLE users ADD COLUMN IF NOT EXISTS auth_id TEXT;
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_auth_id ON users(auth_id);

-- One live quote per operator per request. Withdrawn/rejected quotes do not block a new one.
CREATE UNIQUE INDEX IF NOT EXISTS idx_quotes_one_live_per_operator
  ON quotes(request_id, operator_id) WHERE status IN ('pending','accepted');

-- Demo accounts are usable only in test mode (APP_TEST_MODE=true).
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_demo BOOLEAN NOT NULL DEFAULT false;

-- Fixed-window rate limits (src/lib/rate-limit.ts).
CREATE TABLE IF NOT EXISTS rate_limits (
  key          TEXT PRIMARY KEY,
  window_start TIMESTAMPTZ NOT NULL,
  count        INTEGER NOT NULL DEFAULT 0
);
-- Operator cancellation policy, JSON: {"full_refund_hours":72,"partial_refund_hours":24,"partial_refund_bps":5000}.
-- NULL means the platform default.
ALTER TABLE operators ADD COLUMN IF NOT EXISTS cancellation_policy TEXT;

-- Change requests on a booked trip. The traveler proposes new legs, passenger
-- count or notes. The winning operator accepts (optionally at a new all-in
-- price) or declines. applied_at is set once the booking has been updated:
-- immediately, or when the traveler has paid a higher price.
CREATE TABLE IF NOT EXISTS change_requests (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id               INTEGER NOT NULL REFERENCES booking_requests(id),
  requested_by             INTEGER NOT NULL REFERENCES users(id),
  status                   TEXT NOT NULL DEFAULT 'pending'
                           CHECK(status IN ('pending','accepted','declined','withdrawn')),
  proposed_legs            TEXT NOT NULL,   -- JSON array of {originCode,destCode,departureDate,departureTime}
  proposed_passenger_count INTEGER NOT NULL,
  proposed_notes           TEXT,
  operator_note            TEXT,
  new_price_cents          BIGINT,
  previous_price_cents     BIGINT,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at              TIMESTAMPTZ,
  applied_at               TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_change_requests_request ON change_requests(request_id);

-- A payment for the price difference of an accepted change request.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS change_request_id INTEGER REFERENCES change_requests(id);

-- In-app messages between a traveler and one operator about one request.
-- A thread is (request_id, operator_id). Contact details never appear here.
CREATE TABLE IF NOT EXISTS messages (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id     INTEGER NOT NULL REFERENCES booking_requests(id),
  operator_id    INTEGER NOT NULL REFERENCES operators(id),
  sender_user_id INTEGER NOT NULL REFERENCES users(id),
  body           TEXT NOT NULL CHECK(length(body) <= 2000),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  read_at        TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_messages_thread ON messages(request_id, operator_id, id);

-- When the last "new message" email went out per thread and side, for throttling.
CREATE TABLE IF NOT EXISTS message_notifications (
  request_id   INTEGER NOT NULL REFERENCES booking_requests(id),
  operator_id  INTEGER NOT NULL REFERENCES operators(id),
  recipient    TEXT NOT NULL CHECK(recipient IN ('customer','operator')),
  last_sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (request_id, operator_id, recipient)
);

-- Staff alert subscriptions for change requests and traveler messages.
ALTER TABLE operator_staff ADD COLUMN IF NOT EXISTS on_change INTEGER NOT NULL DEFAULT 1;
ALTER TABLE operator_staff ADD COLUMN IF NOT EXISTS on_message INTEGER NOT NULL DEFAULT 1;

-- Quote revisions: the price before each change, so the traveler sees history.
ALTER TABLE quotes ADD COLUMN IF NOT EXISTS previous_price_cents BIGINT;
ALTER TABLE quotes ADD COLUMN IF NOT EXISTS revised_at TIMESTAMPTZ;

-- Aircraft identity from the FAA registry (src/lib/faa/registry.ts).
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS serial_number TEXT;
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS manufacturer TEXT;
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS model TEXT;
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS faa_record TEXT;          -- JSON RegistryRecord at last lookup
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS faa_checked_at TIMESTAMPTZ;
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ;

-- Aircraft photos, resized in the browser before upload. Bytes live in the
-- database so photos need no separate storage service. Move to object storage
-- if the fleet library grows large.
CREATE TABLE IF NOT EXISTS aircraft_photos (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aircraft_id   INTEGER NOT NULL REFERENCES aircraft(id) ON DELETE CASCADE,
  position      INTEGER NOT NULL DEFAULT 0,
  content_type  TEXT NOT NULL CHECK(content_type IN ('image/jpeg','image/png','image/webp')),
  width         INTEGER,
  height        INTEGER,
  bytes         BYTEA NOT NULL,
  thumb         BYTEA,
  caption       TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_aircraft_photos_aircraft ON aircraft_photos(aircraft_id, position);

-- Autopilot: the operator's pricing parameters (src/lib/quotes/autopilot.ts), JSON.
ALTER TABLE operators ADD COLUMN IF NOT EXISTS autopilot TEXT;

-- Quotes drafted by Autopilot, waiting for a staffer to review and submit.
-- Never shown to travelers. Submitting creates a normal row in quotes.
CREATE TABLE IF NOT EXISTS quote_drafts (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id   INTEGER NOT NULL REFERENCES booking_requests(id),
  operator_id  INTEGER NOT NULL REFERENCES operators(id),
  aircraft_id  INTEGER REFERENCES aircraft(id) ON DELETE SET NULL,
  price_cents  BIGINT NOT NULL,
  message      TEXT,
  valid_until  TEXT,
  worksheet    TEXT NOT NULL,
  flags        TEXT NOT NULL DEFAULT '[]',
  status       TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','submitted','discarded')),
  quote_id     INTEGER REFERENCES quotes(id) ON DELETE SET NULL,
  reviewed_by  INTEGER REFERENCES users(id),
  reviewed_at  TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(request_id, operator_id)
);

-- What Autopilot applied from earlier quotes, shown to the reviewer.
ALTER TABLE quote_drafts ADD COLUMN IF NOT EXISTS notes TEXT;

-- Autopilot learning: weighted averages of how each operator actually prices
-- (src/lib/quotes/learning.ts). Updated on every submitted or revised quote.
CREATE TABLE IF NOT EXISTS autopilot_learning (
  operator_id  INTEGER PRIMARY KEY REFERENCES operators(id),
  data         TEXT NOT NULL,
  samples      INTEGER NOT NULL DEFAULT 0,
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Platform settings set from the admin UI (e.g. Stripe webhook signing secrets
-- created by the Stripe setup button). Server-side only.
CREATE TABLE IF NOT EXISTS platform_settings (
  key         TEXT PRIMARY KEY,
  value       TEXT NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Which booking form produced the request ('ticket' or 'classic'), to compare them.
ALTER TABLE booking_requests ADD COLUMN IF NOT EXISTS form_variant TEXT;

-- Operator pricing defaults per aircraft, for the quote worksheet. Private to the operator.
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS hourly_rate_cents BIGINT;
ALTER TABLE aircraft ADD COLUMN IF NOT EXISTS cruise_ktas INTEGER;

-- The operator's working for a quote (src/lib/quotes/worksheet.ts). Private to
-- the quoting operator: no traveler or admin route reads this table.
CREATE TABLE IF NOT EXISTS quote_worksheets (
  quote_id     INTEGER PRIMARY KEY REFERENCES quotes(id) ON DELETE CASCADE,
  operator_id  INTEGER NOT NULL REFERENCES operators(id),
  inputs       TEXT NOT NULL,
  total_cents  BIGINT NOT NULL,
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
`;

/**
 * Statements that contain semicolons of their own (DO blocks), run after
 * SCHEMA. Each must be idempotent.
 */
export const SCHEMA_BLOCKS: string[] = [
  // Add 'expired' to quotes.status. Guarded so it runs once per database.
  `DO $$
  BEGIN
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid = c.conrelid
      WHERE t.relname = 'quotes' AND c.conname = 'quotes_status_check' AND pg_get_constraintdef(c.oid) LIKE '%expired%'
    ) THEN
      ALTER TABLE quotes DROP CONSTRAINT IF EXISTS quotes_status_check;
      ALTER TABLE quotes ADD CONSTRAINT quotes_status_check
        CHECK (status IN ('pending','accepted','rejected','withdrawn','expired'));
    END IF;
  END $$`,
];
